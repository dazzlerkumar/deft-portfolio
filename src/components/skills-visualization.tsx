// Glass Progress Bar Component
const GlassProgressBar: React.FC<{ 
  skill: Skill; 
  delay: number; 
  inView: boolean;
}> = ({ skill, delay, inView }) => {
  const [progress, setProgress] = useState(0);
  
  useEffect(() => {
    if (inView) {
      const timer = setTimeout(() => {
        setProgress(skill.level);
      }, delay);
      return () => clearTimeout(timer);
    }
  }, [inView, skill.level, delay]);

  return (
    <div className="space-y-3">
      <div className="flex items-center justify-between">
        <div className="flex items-center space-x-3">
          <div className="w-8 h-8 glass-circle">
            <TechIcon 
              name={skill.name} 
              color={skill.color || '#ffffff'} 
              className="w-5 h-5"
            />
          </div>
          <div>
            <h4 className="text-white font-medium">{skill.name}</h4>
            <p className="text-zinc-400 text-sm">{skill.yearsOfExperience} years</p>
          </div>
        </div>
        <span className="text-accent-blue-300 font-semibold">{skill.level}%</span>
      </div>
      
      <div className="relative h-2 glass-progress-track">
        <motion.div
          className="absolute inset-y-0 left-0 glass-progress-fill"
          initial={{ width: 0 }}
          animate={{ width: inView ? `${progress}%` : 0 }}
          transition={{ 
            duration: 1.5, 
            delay: delay / 1000,
            ease: "easeOut" 
          }}
          style={{
            background: `linear-gradient(90deg, ${skill.color || '#3b82f6'}, ${skill.color || '#3b82f6'}80)`,
          }}
        />
      </div>
    </div>
  );
};

